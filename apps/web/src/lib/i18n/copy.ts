export type CopyKey = keyof typeof trCopy;
export type CopyTranslate = (key: CopyKey, values?: TranslationValues) => string;

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export function localizeCopy(locale: Locale, key: CopyKey, values?: TranslationValues): string {
  return interpolate(locale === "tr" ? trCopy[key] : key, values);
}

export function createCopyTranslator(locale: Locale): CopyTranslate {
  return (key, values) => localizeCopy(locale, key, values);
}

export function localizeKnownCopy(locale: Locale, value: string): string {
  if (locale !== "tr" || !Object.hasOwn(trCopy, value)) return value;
  return trCopy[value as CopyKey];
}

type PluralKey = Extract<CopyKey, `{{count}} ${string}`>;

/** Picks the singular or plural English source key for `count`; Turkish uses one form for both. */
export function countLabel(
  c: CopyTranslate,
  count: number,
  singular: PluralKey,
  plural: PluralKey,
): string {
  return c(count === 1 ? singular : plural, { count });
}
